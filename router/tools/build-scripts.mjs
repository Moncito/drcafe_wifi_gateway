// Builds router/01-scripts.rsc from the readable sources in router/src/.
// Usage (from the repo root):  node router/tools/build-scripts.mjs
// Each src/drc-*.rsc becomes one /system script with a correctly escaped source.
// "#@include _file.rsc" lines are replaced by that file. Comment and blank lines
// are dropped from the stored source (they stay readable in src/).
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const routerDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = join(routerDir, "src");

const POLICY = {
  "drc-backup": "ftp,read,write,policy,test,sensitive",
};
const DEFAULT_POLICY = "read,write,test";

function expand(file, seen = new Set()) {
  if (seen.has(file)) throw new Error(`include loop at ${file}`);
  seen.add(file);
  const text = readFileSync(join(srcDir, file), "utf8").replace(/\r\n/g, "\n");
  return text.split("\n").flatMap((line) => {
    const m = line.match(/^\s*#@include\s+(\S+)\s*$/);
    return m ? expand(m[1], new Set(seen)) : [line];
  });
}

function codeLines(file) {
  return expand(file)
    .map((l) => l.replace(/\t/g, "  ").replace(/\s+$/, ""))
    .filter((l) => l.trim() !== "" && !l.trim().startsWith("#"));
}

// RouterOS string escaping: backslash, quote, dollar, question mark.
const esc = (s) => s.replace(/[\\"$?]/g, (c) => "\\" + c);

function toRouterString(lines) {
  // Same layout as /export: each line ends with \r\ and the next starts with \n
  return '"' + lines.map(esc).join('\\r\\\n    \\n') + '"';
}

const files = readdirSync(srcDir).filter((f) => /^drc-.*\.rsc$/.test(f)).sort();
// drc-epoch must exist before anything parses it
files.sort((a, b) => (a === "drc-epoch.rsc" ? -1 : b === "drc-epoch.rsc" ? 1 : 0));

let out = `# 01-scripts.rsc - GENERATED by router/tools/build-scripts.mjs
# Do not edit by hand: change router/src/*.rsc and rebuild.
# Installs the Don Robert Cafe Wi-Fi scripts. Safe to re-import (replaces them).
`;
for (const f of files) {
  const name = f.replace(/\.rsc$/, "");
  const lines = codeLines(f);
  if (lines.some((l) => l.length > 400)) throw new Error(`${f}: line too long`);
  out += `
/system script remove [find where name="${name}"]
/system script add name=${name} policy=${POLICY[name] ?? DEFAULT_POLICY} dont-require-permissions=no comment="Don Robert Cafe Wi-Fi" source=${toRouterString(lines)}
`;
}
writeFileSync(join(routerDir, "01-scripts.rsc"), out.replace(/\n/g, "\r\n"));
console.log(`wrote router/01-scripts.rsc (${files.length} scripts: ${files.join(", ")})`);
